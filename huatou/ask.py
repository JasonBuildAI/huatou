"""「她有没有在问他」—— 这一档判据的**唯一实现**（`docs/rules.md` §1）。

判据**不是**「带问号」：真机上她那串自问自答的两句问号都没有，紧接着的定时主动
就把话续上了，用户读到的就是「她替我答了」。所以这一档认六种形状，按优先级
从上往下判，任一命中即为真。

表达层做「剥掉自问自答」时也读这一份 —— 它只有这一个实现，谁要用谁 import，
不许在别处照着写一遍（硬约束 8：评测与实现同源就等于没有评测）。
"""
from __future__ import annotations

import re

__all__ = ["asks_the_user", "ends_with_question"]

# 问号收口：先把尾部那串引号 / 括号削掉再判，否则「真的吗？」后面缀个引号就漏了。
_QUESTION_TAIL = re.compile(r"[？?][”\"'’）)】\]》」』]*\s*$")

# 第二种形状：**疑问词**。真机 2026-09-23 那轮通话的「最近怎么了呀」——没有问号、
# 也没有第二人称，只认问号与语气词的老判据一个字都没管，紧接着的「画廊事多，
# 还是没睡好」于是被当成她自己的续话送了出去，用户读到的就是「她替我答了」。
# 疑问词不靠人称也站得住，所以这一档不看第二人称；否定的那几种形状先排除掉
# （没什么 / 不怎么 / 哪有 / 别无）—— 它们是陈述，不是问句。
# 「干嘛 / 啥」刻意不收、「几遍 / 几次」没有跟着放宽：语料与理由见 docs/rules.md §1.2。
_Q_WORD = re.compile(
    r"(?<![没不别无])什么|(?<![没不])怎么|咋|哪[儿里个天]|几点|多少|谁|几[个天]"
    r"|是不是|有没有|要不要|好不[好嘛]|行不行|知不知道|记不记得|想不想"
    r"|(?<=[，,])还是")


# 第三种形状：「吗」**不挑位置**。真机 2026-09-23 23:04「还没哦，画到一半。你呢，
# 今天不是坐了很久地铁吗，现在到哪了」—— 收口是「到哪了」，只认收口的老判据认不出，
# 紧接着那轮定时主动就接上来把话续了。句中的「么」**不能照搬**这一格：它同样长在
# 「这么 / 那么 / 多么」里，量过语料一条都没多认（`docs/rules.md` §1.2）。
_MA_ANYWHERE = "吗"

def ends_with_question(s: str) -> bool:
    """这一段是不是以问号收口（尾部引号 / 括号不算数）。"""
    return bool(_QUESTION_TAIL.search(str(s or "").strip()))


def asks_the_user(s: str) -> bool:
    """她这一条是不是在**问他**。

    只回答「问过没有」这一件事。用它的地方都把「问过」当成停下来的理由。
    """
    t = str(s or "").strip()
    if ends_with_question(t):
        return True
    if _Q_WORD.search(t):
        return True
    return _MA_ANYWHERE in t
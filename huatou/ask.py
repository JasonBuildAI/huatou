"""「她有没有在问他」—— 这一档判据的**唯一实现**（`docs/rules.md` §1）。

判据**不是**「带问号」：真机上她那串自问自答的两句问号都没有，紧接着的定时主动
就把话续上了，用户读到的就是「她替我答了」。所以这一档认六种形状，按优先级
从上往下判，任一命中即为真。

表达层做「剥掉自问自答」时也读这一份 —— 它只有这一个实现，谁要用谁 import，
不许在别处照着写一遍（硬约束 8：评测与实现同源就等于没有评测）。
"""
from __future__ import annotations

import re

__all__ = ["asks_the_user", "ends_with_question"]

# 问号收口：先把尾部那串引号 / 括号削掉再判，否则「真的吗？」后面缀个引号就漏了。
_QUESTION_TAIL = re.compile(r"[？?][”\"'’）)】\]》」』]*\s*$")

# 第二种形状：**疑问词**。真机 2026-09-23 那轮通话的「最近怎么了呀」——没有问号、
# 也没有第二人称，只认问号与语气词的老判据一个字都没管，紧接的那半句续话于是
# 被当成她自己的话送了出去，用户读到的就是「她替我答了」。
# 疑问词不靠人称也站得住，所以这一档不看第二人称；否定的那几种形状先排除掉
# （没什么 / 不怎么 / 哪有 / 别无）—— 它们是陈述，不是问句。
# 「干嘛 / 啥」刻意不收、「几遍 / 几次」没有跟着放宽：语料与理由见 docs/rules.md §1.2。
_Q_WORD = re.compile(
    r"(?<![没不别无])什么|(?<![没不])怎么|咋|哪[儿里个天]|几点|多少|谁|几[个天]"
    r"|是不是|有没有|要不要|好不[好嘛]|行不行|知不知道|记不记得|想不想"
    r"|(?<=[，,])还是")


# 第三种形状：「吗」**不挑位置**。真机 2026-09-23 23:04「还没哦，画到一半。你呢，
# 今天不是坐了很久地铁吗，现在到哪了」—— 收口是「到哪了」，只认收口的老判据认不出，
# 紧接着那轮定时主动就接上来把话续了。句中的「么」**不能照搬**这一格：它同样长在
# 「这么 / 那么 / 多么」里，量过语料一条都没多认（`docs/rules.md` §1.2）。
_MA_ANYWHERE = "吗"

# 收口处的杂音：引号、括号、句末标点、空白都不算句子的一部分 —— 判「收口在哪」
# 之前先削掉它们，否则「你到宿舍了没。」会差一个字符。
_TAIL_PUNCT = re.compile(r"[”\"'’）)】\]》」』。！!…~～\s]+$")

# 第四种形状：**A 不 A**，收口在一个裸「没」上。真机语料里她这一档只有三句
# （「你到宿舍了没」「那起来之后吃了东西没」「你今天坐了那么久地铁到家了没」），
# 全部在问他。问句前面一定垫着一个成分；光一个「没」或「还没」是他的回答，
# 不在这一档 —— 所以否定前缀（还不也都没）要挡住。
_A_NOT_A_TAIL = re.compile(r"(?<![还不也都没])没$")

# 第五 / 第六种形状：收口的语气词，分两档。
#   硬档「吗」「么」：它们本身就把句子变成问句（「吗」上一格已经接住，这里管「么」）。
#   软档「吧呢呀啊呗嘛」：得靠句中的第二人称才认 ——「那就快去睡吧」没有第二人称，
#   那是叮嘱不是问句。「嘛」与「吗」同族，但它还兼着「快来嘛」这种撒娇 / 催促，
#   所以跟软档走：真机那串自问自答里的「你不是说这几天要调养嘛」正是靠这一档认出来的。
# 认错与认漏的代价不对等，这一档偏保守：认错（把招呼、道谢认成问句）只是让她少说一句，
# 认漏就是她替他把答案说了。账在 docs/rules.md §1.3。
_ASK_PARTICLE_HARD = "吗么"
_ASK_PARTICLE_SOFT = "吧呢呀啊呗嘛"
_SECOND_PERSON = ("你", "您", "咱")

def ends_with_question(s: str) -> bool:
    """这一段是不是以问号收口（尾部引号 / 括号不算数）。"""
    return bool(_QUESTION_TAIL.search(str(s or "").strip()))


def asks_the_user(s: str) -> bool:
    """她这一条是不是在**问他**。

    只回答「问过没有」这一件事。用它的地方都把「问过」当成停下来的理由。
    """
    t = str(s or "").strip()
    if ends_with_question(t):
        return True
    if _Q_WORD.search(t):
        return True
    if _MA_ANYWHERE in t:
        return True
    body = _TAIL_PUNCT.sub("", t)
    if _A_NOT_A_TAIL.search(body):
        return True
    last = body[-1:]
    if not last:
        return False
    if last in _ASK_PARTICLE_HARD:
        return True
    return last in _ASK_PARTICLE_SOFT and any(c in t for c in _SECOND_PERSON)